/**
 * ГДЕ ИСКАТЬ СЕРВЕРА
 *
 * Игрок не должен знать никаких адресов. Игра сама обходит этот список,
 * находит живой сервер и подключается к нему — а дальше человек просто
 * выбирает сервер из списка по названию.
 *
 * Откуда берутся адреса:
 *   • ОБЩИЕ      — сервера в интернете, работают для всех и всегда;
 *   • вшитые     — адрес этого компьютера в домашней сети. Его кладёт
 *                  СОБРАТЬ-ИГРУ.py прямо внутрь готового файла, поэтому
 *                  на телефоне и у друга в том же Wi-Fi всё находится само;
 *   • ДОМА       — сам компьютер, если игру открыли на нём же.
 *
 * Честно про важное: сервера не появляются сами по себе. Каждый адрес —
 * это компьютер, который где-то работает. Домашний адрес работает, пока
 * ИГРАТЬ.bat открыт и оба устройства в одном Wi-Fi. Чтобы сервер жил
 * всегда — выложите его в интернет (СЕРВЕР-В-ИНТЕРНЕТЕ.md) и впишите
 * адрес в ОБЩИЕ ниже.
 */
(function (global) {
  'use strict';
  const KM = global.KM;

  // ------------------------------------------------------------
  //  СЮДА ВПИСЫВАТЬ АДРЕС ОБЩЕГО СЕРВЕРА
  //  Одна строчка — и все игроки увидят его сами.
  // ------------------------------------------------------------
  const ОБЩИЕ = [
    // { host: 'kotiki-magi.onrender.com', name: 'Общий сервер' },
  ];

  // Свой компьютер: ИГРАТЬ.bat поднимает сервер именно тут.
  const ДОМА = [
    { host: 'localhost:8765', name: 'Этот компьютер' },
    { host: '127.0.0.1:8765', name: 'Этот компьютер' },
  ];

  const ПОРТ = KM.SERVER_PORT || 8765;

  /** Все адреса, которые стоит попробовать, в порядке предпочтения. */
  function candidates(saved) {
    const out = [];
    const были = new Set();
    const add = (host, name) => {
      if (!host) return;
      const k = String(host).toLowerCase();
      if (были.has(k)) return;
      были.add(k);
      out.push({ host: host, name: name || host });
    };

    // 1. То, что игрок вписал руками, — всегда важнее прочего
    if (saved) add(saved, 'Ваш адрес');

    // 2. Игра открыта с сайта — значит, сервер, скорее всего, там же
    const l = global.location;
    if (l && l.protocol !== 'file:' && l.host) add(l.host, 'Этот сайт');

    // 3. Общие сервера в интернете
    for (const s of ОБЩИЕ) add(s.host, s.name);

    // 4. Адрес, вшитый при сборке: домашний компьютер с ИГРАТЬ.bat.
    //    Ради него всё и затевалось — на телефоне «localhost» бесполезен.
    //    Порт пробуем не один: если 8765 был занят, сервер взял соседний.
    for (const h of (KM.SERVER_LIST || [])) {
      add(h, 'Домашний компьютер');
      const дом = String(h).split(':')[0];
      for (let порт = ПОРТ; порт < ПОРТ + 6; порт++) {
        add(дом + ':' + порт, 'Домашний компьютер');
      }
    }

    // 5. Сам компьютер — последним: он есть далеко не всегда
    for (const s of ДОМА) add(s.host, s.name);
    for (let порт = ПОРТ; порт < ПОРТ + 6; порт++) {
      add('localhost:' + порт, 'Этот компьютер');
    }

    return out;
  }

  /**
   * Адреса всей домашней сети — на случай, если роутер выдал компьютеру
   * другой номер. Обходим соседей по той же подсети, что была при сборке.
   */
  function neighbours() {
    const out = [];
    for (const сеть of (KM.SUBNETS || [])) {
      for (let i = 1; i <= 254; i++) out.push(сеть + i + ':' + ПОРТ);
    }
    return out;
  }

  KM.SERVERS = { ОБЩИЕ, ДОМА, candidates, neighbours, ПОРТ };
})(this);
